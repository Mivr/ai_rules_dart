import 'package:build/build.dart';
import 'package:rules_dart_ext/worker_entry.dart';

/// The corpus's code-generation entry point. It speaks the shim contract so
/// `dart_codegen`, `dart_aggregate_codegen` and `dart_sqlcodegen` exercise
/// their real worker action without pulling a pub builder in.
final class _CorpusBuilder implements Builder {
  @override
  Map<String, List<String>> get buildExtensions => const {
    '.dart': ['.g.dart', '.agg.dart'],
    '.drift': ['.drift.dart'],
  };

  @override
  Future<void> build(BuildStep buildStep) async {
    await buildStep.writeAsString(
      buildStep.allowedOutputs.first,
      '// Generated by the corpus fixture generator.\n',
    );
  }
}

Future<void> main(List<String> args) => shimMain(args, (_) => _CorpusBuilder());
