/// Writes the runner's entry point from the `build.yaml` of builder packages,
/// the way `build_runner` writes `.dart_tool/build/entrypoint/build.dart`.
///
/// Usage: gen_entry --out <entry.dart> [--build-yaml <package>=<path>]...
///
/// Each `build.yaml` is parsed with `package:build_config`, the parser
/// `build_runner` uses. The entry imports every library a builder definition
/// names, maps each builder key to its factories, and carries the text of each
/// `build.yaml`: the runner serves package files only from an action's
/// declared inputs, and a builder package's `build.yaml` is not one of them.
library;

import 'dart:io';

import 'package:build_config/build_config.dart';

void main(List<String> args) {
  String? out;
  final yamls = <String, String>{};
  for (var i = 0; i < args.length; i++) {
    switch (args[i]) {
      case '--out':
        out = args[++i];
      case '--build-yaml':
        final kv = args[++i];
        final eq = kv.indexOf('=');
        yamls[kv.substring(0, eq)] = File(kv.substring(eq + 1)).readAsStringSync();
      default:
        stderr.writeln('gen_entry: unknown argument ${args[i]}');
        exit(2);
    }
  }
  if (out == null) {
    stderr.writeln('gen_entry: --out is required');
    exit(2);
  }

  final imports = <String, String>{};
  final builders = <String, List<String>>{};
  final postProcess = <String, String>{};
  String prefixFor(String import) =>
      imports.putIfAbsent(import, () => '_i${imports.length + 1}');

  for (final package in yamls.keys.toList()..sort()) {
    final parsed = BuildConfig.parse(package, const [], yamls[package]!);
    // A builder whose library is not a `package:` URI is one the package
    // uses on itself (a relative import); it cannot run for another package.
    for (final b in parsed.builderDefinitions.values) {
      if (!b.import.startsWith('package:')) continue;
      final prefix = prefixFor(b.import);
      builders[b.key] = [for (final f in b.builderFactories) '$prefix.$f'];
    }
    for (final b in parsed.postProcessBuilderDefinitions.values) {
      if (!b.import.startsWith('package:')) continue;
      postProcess[b.key] = '${prefixFor(b.import)}.${b.builderFactory}';
    }
  }

  final buffer = StringBuffer()
    ..writeln('// Generated by gen_entry from the build.yaml of the builder')
    ..writeln('// packages in the lock. Do not edit.')
    ..writeln('// ignore_for_file: type=lint, implementation_imports')
    ..writeln(
      "import 'package:build_runner/src/build_plan/builder_factories.dart' as _b;",
    )
    ..writeln("import 'package:rules_dart_build_runner/runner.dart' as _r;");
  for (final e in imports.entries) {
    buffer.writeln("import '${e.key}' as ${e.value};");
  }
  buffer.writeln('final _factories = _b.BuilderFactories({');
  for (final k in builders.keys.toList()..sort()) {
    buffer.writeln("  '$k': [${builders[k]!.join(', ')}],");
  }
  buffer.writeln('}, postProcessBuilderFactories: {');
  for (final k in postProcess.keys.toList()..sort()) {
    buffer.writeln("  '$k': ${postProcess[k]},");
  }
  buffer.writeln('});');
  buffer.writeln('const _buildYamls = <String, String>{');
  for (final k in yamls.keys.toList()..sort()) {
    buffer.writeln("  '$k': ${_literal(yamls[k]!)},");
  }
  buffer.writeln('};');
  buffer.writeln(
    'Future<void> main(List<String> args) => '
    '_r.runnerMain(args, _factories, _buildYamls);',
  );
  File(out).writeAsStringSync(buffer.toString());
}

String _literal(String s) {
  final b = StringBuffer("'");
  for (final c in s.runes) {
    switch (c) {
      case 0x5c:
        b.write(r'\\');
      case 0x27:
        b.write(r"\'");
      case 0x24:
        b.write(r'\$');
      case 0x0a:
        b.write(r'\n');
      case 0x0d:
        b.write(r'\r');
      default:
        b.writeCharCode(c);
    }
  }
  b.write("'");
  return b.toString();
}
