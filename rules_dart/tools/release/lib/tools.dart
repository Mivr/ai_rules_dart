/// The prebuilt tools of a release: building them on one platform, and the
/// table the released module reads them through.
///
/// A release job on each platform's runner builds the module's tool set
/// (`prebuilt_set`) twice, in two consumer-shaped workspaces with separate
/// output bases and no cache, and ships it only when the two builds agree
/// byte for byte (`tools build`). The release script then gathers what the
/// jobs built, names each archive after the release, and writes the table
/// into the module's source archive (`tools table`). A platform whose build
/// was not reproducible ships nothing and builds its tools from source; a
/// build that fails fails the job, and the release with it: a platform may
/// be absent, never wrong.
library;

import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

/// What one module prebuilds.
final class ToolSet {
  /// Creates a tool set record.
  const ToolSet({
    required this.module,
    required this.target,
    required this.table,
    required this.versionKey,
    required this.overrides,
  });

  /// The module's directory: `rules_dart`.
  final String module;

  /// The tool-set target, as a consumer names it.
  final String target;

  /// The table's path inside the module.
  final String table;

  /// The `tools.json` field that holds the version the table is keyed by.
  final String versionKey;

  /// The modules of this repository the consumer workspace takes from the
  /// checkout, by directory, with their module and repository names.
  final List<({String dir, String module, String repo})> overrides;
}

const _dart = (dir: 'rules_dart', module: 'ai_rules_dart', repo: 'rules_dart');
const _flutter = (
  dir: 'rules_flutter',
  module: 'ai_rules_flutter',
  repo: 'rules_flutter',
);

