/// The host platforms the SDK tables list, as the tables name them.
const List<String> platforms = [
  'linux-arm64',
  'linux-x64',
  'macos-arm64',
  'macos-x64',
  'windows-x64',
];

/// The `MODULE.bazel` of a workspace that uses [set]'s modules from the
/// checkout at [root], as a consumer would use the released ones: the
/// repositories get the names they have in a consumer's build, so the
/// snapshots record the paths a consumer's own source build records.
String consumerModule(ToolSet set, String root) {
  final buffer = StringBuffer(
    '# Generated by `release tools build`: a consumer of the checkout.\n'
    'module(name = "prebuilt_tools_build")\n',
  );
  for (final o in set.overrides) {
    final String path = '$root/${o.dir}'.replaceAll(r'\', '/');
    buffer
      ..writeln()
      ..writeln(
        'bazel_dep(name = "${o.module}", version = "0.0.0", '
        'repo_name = "${o.repo}")',
      )
      ..writeln(
        'local_path_override(module_name = "${o.module}", path = "$path")',
      );
  }
  return buffer.toString();
}

/// The Bazel arguments for [command] in consumer workspace number [n] under
/// [work]: a startup `--output_base` of its own comes first.
///
/// A user rc may fix the output base for every Bazel run in the job (the
/// setup-bazel action writes `startup --output_base=...` to `~/.bazelrc`,
/// `$HOME/.cache/bazel` on Linux and macOS and `D:/_bazel` on Windows), and
/// two workspaces that share one output base share its action cache: the
/// second build then finds the first one's outputs (28 of 29 actions were
/// cache hits in the first rehearsal) and the byte-for-byte comparison
/// compares a build with itself. A startup option on the command line wins over
/// the rc, so each workspace gets its own base beside it.
List<String> consumerBazelArgs(String work, int n, List<String> command) => [
  '--output_base=${'$work/output_base-$n'.replaceAll(r'\', '/')}',
  ...command,
];

/// The files of one built set: the published path inside the archive to its
/// bytes. `tools.json` is among them.
typedef SetFiles = Map<String, List<int>>;

/// The directory of a set that holds the pub archive scanner, which ships as
/// an archive of its own: a Flutter workspace needs it, and nothing else of
/// rules_dart's set.
const String pubScannerDir = 'pub_scanner/';

/// [files] split into the tools archive and the scanner's (`pub_scanner/`,
/// with that directory taken off the paths); the second is empty for a set
/// without a scanner.
({SetFiles tools, SetFiles scanner}) splitSet(SetFiles files) {
  final tools = <String, List<int>>{};
  final scanner = <String, List<int>>{};
  for (final MapEntry<String, List<int>> e in files.entries) {
    if (e.key.startsWith(pubScannerDir)) {
      scanner[e.key.substring(pubScannerDir.length)] = e.value;
    } else {
      tools[e.key] = e.value;
    }
  }
  return (tools: tools, scanner: scanner);
}

/// The paths whose bytes differ between two builds of a set, or that only
/// one of them has. Empty when the builds are reproducible.
List<String> differences(SetFiles a, SetFiles b) {
  final keys = <String>{...a.keys, ...b.keys}.toList()..sort();
  final out = <String>[];
  for (final k in keys) {
    final List<int>? x = a[k];
    final List<int>? y = b[k];
    if (x == null || y == null) {
      out.add('$k: only in build ${x == null ? 2 : 1}');
    } else if (sha256.convert(x) != sha256.convert(y)) {
      out.add('$k: ${sha256.convert(x)} != ${sha256.convert(y)}');
    }
  }
  return out;
}

/// A tar archive of [files], gzip-compressed: entries sorted by path, every
/// one a regular file owned by 0:0 at time 0, executable unless it is JSON.
/// The same files give the same bytes.
List<int> tarGz(SetFiles files) {
  final out = BytesBuilder();
  final names = files.keys.toList()..sort();
  for (final name in names) {
    final List<int> data = files[name]!;
    out.add(
      _ustarHeader(name, data.length, name.endsWith('.json') ? 420 : 493),
    );
    out.add(data);
    final int pad = (512 - data.length % 512) % 512;
    out.add(List<int>.filled(pad, 0));
  }
  out.add(List<int>.filled(1024, 0));
  return GZipCodec(level: 9).encode(out.takeBytes());
}

List<int> _ustarHeader(String name, int size, int mode) {
  final List<int> path = utf8.encode(name);
  if (path.length > 100) {
    throw FormatException('tar: path longer than 100 bytes: $name');
  }
  final header = List<int>.filled(512, 0);
  void put(int at, List<int> bytes) =>
      header.setRange(at, at + bytes.length, bytes);
  String octal(int v, int width) =>
      '${v.toRadixString(8).padLeft(width - 1, '0')}\x00';
  put(0, path);
  put(100, ascii.encode(octal(mode, 8)));
  put(108, ascii.encode(octal(0, 8)));
  put(116, ascii.encode(octal(0, 8)));
  put(124, ascii.encode(octal(size, 12)));
  put(136, ascii.encode(octal(0, 12)));
  put(148, List<int>.filled(8, 32));
  header[156] = 48; // '0': a regular file.
  put(257, ascii.encode('ustar\x00'));
  put(263, ascii.encode('00'));
  final int sum = header.fold(0, (a, b) => a + b);
  put(148, ascii.encode('${sum.toRadixString(8).padLeft(6, '0')}\x00 '));
  return header;
}

/// What a platform's job leaves for the release script: `tools-<platform>.json`
/// beside `tools-<platform>.tar.gz` and, for rules_dart,
/// `pub_scanner-<platform>.tar.gz` (both absent when not reproducible).
final class Sidecar {
  /// Creates a sidecar record.
  const Sidecar({
    required this.module,
    required this.platform,
    required this.version,
    required this.sha256,
    required this.problems,
    this.pubScannerSha256,
  });

  /// Reads a sidecar file's text.
  factory Sidecar.parse(String text) {
    final Object? doc = jsonDecode(text);
    if (doc is! Map<String, Object?>) {
      throw const FormatException('a tools sidecar must be a JSON object');
    }
    final Object? module = doc['module'];
    final Object? platform = doc['platform'];
    final Object? version = doc['version'];
    final Object? digest = doc['sha256'];
    final Object? problems = doc['problems'];
    final Object? scanner = doc['pub_scanner_sha256'];
    if (module is! String ||
        platform is! String ||
        version is! String ||
        (digest != null && digest is! String) ||
        (scanner != null && scanner is! String) ||
        problems is! List<Object?>) {
      throw const FormatException(
        'a tools sidecar needs module, platform, version, sha256 and problems',
      );
    }
    return Sidecar(
      module: module,
      platform: platform,
      version: version,
      sha256: digest as String?,
      problems: problems.cast<String>(),
      pubScannerSha256: scanner as String?,
    );
  }

  /// The module directory.
  final String module;

  /// The platform key.
  final String platform;

  /// The version the table keys the archive by.
  final String version;

  /// The archive's checksum; null when nothing ships.
  final String? sha256;

  /// Why nothing ships (the bytes that differed between the two builds).
  final List<String> problems;

  /// The scanner archive's checksum; null when the set has no scanner or
  /// nothing ships.
  final String? pubScannerSha256;

  /// The base name of the job's files.
  static String baseName(String platform) => 'tools-$platform';

  /// The file name of the job's scanner archive.
  static String scannerName(String platform) => 'pub_scanner-$platform.tar.gz';

  /// The sidecar's text.
  String encode() =>
      '${const JsonEncoder.withIndent('  ').convert({'module': module, 'platform': platform, 'version': version, 'sha256': sha256, if (pubScannerSha256 != null) 'pub_scanner_sha256': pubScannerSha256, 'problems': problems})}\n';
}

/// The release asset name of a platform's archive.
String assetName(String tag, String version, String platform) =>
    '$tag-tools-$version-$platform.tar.gz';

/// The release asset name of a platform's scanner archive.
String scannerAssetName(String tag, String platform) =>
    '$tag-pub_scanner-$platform.tar.gz';

/// The table a released module reads, from the sidecars the jobs left.
///
/// [archives] maps a sidecar to its archive's bytes (null when it ships
/// none), and [scanners] to its scanner archive's. Throws a
/// [FormatException] for a sidecar of another module, an unknown platform,
/// a platform listed twice, or an archive whose checksum is not the
/// sidecar's.
({Map<String, Object?> table, List<String> absent}) toolsTable({
  required ToolSet set,
  required String tag,
  required String download,
  required Map<Sidecar, List<int>?> archives,
  Map<Sidecar, List<int>?> scanners = const {},
}) {
  final byVersion = <String, Map<String, Object?>>{};
  final scannerTable = <String, Object?>{};
  final seen = <String>{};
  final absent = <String>[];
  final sorted = archives.keys.toList()
    ..sort((a, b) => a.platform.compareTo(b.platform));
  for (final s in sorted) {
    if (s.module != set.module) {
      throw FormatException(
        'sidecar of ${s.module} in ${set.module}\'s release',
      );
    }
    if (!platforms.contains(s.platform)) {
      throw FormatException('sidecar of unknown platform ${s.platform}');
    }
    if (!seen.add(s.platform)) {
      throw FormatException('two sidecars for ${s.platform}');
    }
    final List<int>? bytes = archives[s];
    if (s.sha256 == null) {
      absent.add('${s.platform}: ${s.problems.join('; ')}');
      continue;
    }
    if (bytes == null || sha256.convert(bytes).toString() != s.sha256) {
      throw FormatException(
        'the archive of ${s.platform} is missing or is not ${s.sha256}',
      );
    }
    byVersion.putIfAbsent(s.version, () => {})[s.platform] = {
      'url': '$download/$tag/${assetName(tag, s.version, s.platform)}',
      'sha256': s.sha256,
    };
    final String? scanner = s.pubScannerSha256;
    if (scanner == null) continue;
    final List<int>? scannerBytes = scanners[s];
    if (scannerBytes == null ||
        sha256.convert(scannerBytes).toString() != scanner) {
      throw FormatException(
        'the scanner archive of ${s.platform} is missing or is not $scanner',
      );
    }
    scannerTable[s.platform] = {
      'url': '$download/$tag/${scannerAssetName(tag, s.platform)}',
      'sha256': scanner,
    };
  }
  return (
    table: {
      'release': tag,
      'tools': byVersion,
      if (scannerTable.isNotEmpty) 'pub_scanner': scannerTable,
    },
    absent: absent,
  );
}
